"""Settings › Music: the engine's music library (``vstudio.music``: the downloaded CC0 tracks with their licence,
tempo and energy, the built-in beds), her favourites / bans (``$VSTUDIO_HOME/music.json``, shared with the CLI skill:
a favourite is picked first when it fits, a banned track never) and which of her recent videos used which track.

    GET  /api/music                {dir, installed, total, tracks [...], builtins [...], prefs, recent [...]}
    POST /api/music/prefs          {id, favourite?: bool, banned?: bool} -> the same document

Previews play the track files themselves (``roots``: the library folder and the built-in beds' cache are media
roots of the desk).
"""
import os

from .common import BadRequest, need

PREVIEW_S = 20.0             # the built-in beds are made this long to listen to


def _mu():
    try:
        from vstudio import music as MU
    except ImportError as e:                             # an engine without the music module
        raise BadRequest(f"this engine has no music library ({e})") from None
    return MU


class Music:
    def doc(self):
        MU = _mu()
        pf = MU.prefs()
        fav, ban = set(pf["favourites"]), set(pf["banned"])
        used = {}
        for r in MU.history(limit=MU.RECENT_N * 4):
            used[r["track"]] = used.get(r["track"], 0) + 1
        keep = ("id", "title", "artist", "mood", "style", "tags", "bpm", "energy", "duration", "license", "origin",
                "licence_evidence", "installed", "path", "steady")
        tracks = []
        for t in MU.library():
            row = {k: t.get(k) for k in keep}
            row.update(favourite=t["id"] in fav, banned=t["id"] in ban, uses=used.get(t["id"], 0))
            tracks.append(row)
        builtins = []
        for m, s in MU.STYLES.items():
            tid = f"builtin:{m}"
            try:
                path = MU.make(m, PREVIEW_S)
            except Exception:  # noqa: BLE001  (no numpy here: listed without a preview)
                path = None
            builtins.append(dict(id=tid, title=s["en"], title_zh=s["zh"], mood=m, bpm=s["bpm"], path=path,
                                 license="generated by Reelfold (MIT)", favourite=tid in fav, banned=tid in ban,
                                 uses=used.get(tid, 0)))
        recent = [dict(track=r["track"], title=r.get("title"), at=r.get("at"), group=r.get("group"))
                  for r in reversed(MU.history(limit=MU.RECENT_N))]
        return dict(dir=MU.library_dir(), installed=sum(1 for t in tracks if t["installed"]), total=len(tracks),
                    size=sum((MU.library_track(t["id"]) or {}).get("size") or 0 for t in tracks),
                    tracks=tracks, builtins=builtins, prefs=pf, recent=recent, recent_n=MU.RECENT_N)

    def prefs(self, body):
        MU = _mu()
        need(isinstance(body, dict), "body: {id, favourite?, banned?}")
        tid = body.get("id")
        need(isinstance(tid, str) and (tid.startswith(("lib:", "builtin:")) or os.path.isabs(tid)) and len(tid) < 4096,
             "id: a library / built-in track id or a music file path")
        for k in ("favourite", "banned"):
            need(body.get(k) in (None, True, False), f"{k}: true, false or absent")
        MU.set_pref(tid, favourite=body.get("favourite"), banned=body.get("banned"))
        return self.doc()

    def roots(self):
        """Folders whose files the desk may play (the previews)."""
        try:
            MU = _mu()
        except BadRequest:
            return []
        out = [MU.library_dir()]
        try:
            out.append(MU._cache())
        except Exception:  # noqa: BLE001
            pass
        return [p for p in out if p and os.path.isdir(p)]

    def route(self, method, parts, body, query=None):
        """None = not mine."""
        if parts == ["music"] and method == "GET":
            return self.doc()
        if parts == ["music", "prefs"] and method == "POST":
            return self.prefs(body)
        return None
