"""vlog: render through build_vlog.py (calm; delegates to build_fun.py for style fun), the music pick (checkpoint
``music``: a track from the license-free library, vstudio.music) and the music bed (add_music.py)."""
import json
import os

from vstudio.batch.util import sha1_json, write_json

from ..build import file_sha

# how many library tracks the music checkpoint offers (+ "no music")
N_TRACKS = 3


def _edit(env):
    path = os.path.join(env.item_dir, "work", "edit.json")
    with open(path, encoding="utf-8") as f:
        return path, json.load(f)


def render(env):
    path, cfg = _edit(env)
    argv = [env.fmt("{python}"), os.path.join(env.workflow_dir, "scripts", "build_vlog.py"), path]
    plats = env.params.get("platforms") or []
    if plats:
        argv += ["--platform", plats[0]]
    if cfg.get("style") == "fun":
        argv = [env.fmt("{python}"), os.path.join(env.workflow_dir, "scripts", "build_fun.py"), path]
        if plats:
            argv += ["--platform", plats[0]]
        if env.params.get("preset"):
            argv += ["--preset", env.params["preset"]]
        # the recipe's framing choice reaches the reel too (it used to put landscape drone shots on a blurred fill
        # in a vertical reel whatever she picked): follow = the subject, blur = the whole frame on a blurred fill
        argv += ["--reframe-fallback", "pad-blur" if env.params.get("reframe") == "blur" else "subject"]
    env.run(argv, cwd=os.path.dirname(path), log="build.log")
    out = cfg.get("out") or ("fun_vlog.mp4" if cfg.get("style") == "fun" else "vlog_master.mp4")
    master = out if os.path.isabs(out) else os.path.join(os.path.dirname(path), out)
    if not os.path.exists(master):
        raise RuntimeError(f"vlog render wrote no {master}")
    res = dict(master=master, style=cfg.get("style", "calm"), files=[master], digest=file_sha(master))
    shots = os.path.splitext(master)[0] + ".shots.json"
    if os.path.exists(shots) and os.path.getmtime(shots) >= os.path.getmtime(master) - 5:
        res["shots"] = shots                          # the crossfades, for the export's subject reframe
    return res


# --------------------------------------------------------------------------- the music pick
def _given_track(params):
    t = (params.get("_inputs") or {}).get("music")
    return t[0] if isinstance(t, list) and t else (t or None)


def _request_text(env):
    """Her words for this video: the project's request + name + the item's title (what the pick is matched to)."""
    parts = []
    try:
        import yaml
        with open(os.path.join(env.project_dir, "project.yaml"), encoding="utf-8") as f:
            d = yaml.safe_load(f) or {}
        parts += [str(d.get("prompt") or ""), str(d.get("name") or "")]
    except (OSError, ValueError, ImportError):
        pass
    parts.append(str(env.params.get("title") or ""))
    return "\n".join(p for p in parts if p)


def _duration(path):
    from vstudio import media
    return float(media.probe(path)["duration"])


def _label(t):
    bpm = f", {t['bpm']} BPM" if t.get("bpm") else ""
    if t["source"] == "builtin":
        return dict(en=f"{t['title']} (built-in{bpm})", zh=f"{t.get('title_zh') or t['title']}（内置{bpm}）")
    who = f" - {t['artist']}" if t.get("artist") else ""
    return dict(en=f"{t['title']}{who} ({t['license']})", zh=f"{t['title']}{who}（{t['license']}）")


def _why(t, style, dur):
    from vstudio import music as MU
    return f"{MU.reason(t)}; a {style} vlog, fitted to {dur:.0f} s"


def _edit_shot_s(cfg, fun, bpm=None):
    """The edit's mean shot length (s): a calm film's windows / a reel's beats at its tempo; None when unknown."""
    try:
        if fun:
            beats = [float(x.get("beats") or 2) for x in cfg.get("shots") or []]
            return round(sum(beats) / len(beats) * 60.0 / float(bpm or FUN_BPM), 2) if beats else None
        durs = [float(x["dur"]) for x in cfg.get("segments") or [] if x.get("dur")]
        return round(sum(durs) / len(durs) / max(0.25, calm_speed(cfg)), 2) if durs else None
    except (TypeError, ValueError, ZeroDivisionError):
        return None


def _fun_current(cfg):
    """The reel's own beat track: (library / built-in id or None, its file name in the edit)."""
    return cfg.get("music_track"), cfg.get("music")


def music_payload(env, cp):
    """Options: the library's best fits for her request, the vlog's style and the edit's pace (vstudio.music.rank:
    your own tracks in ~/Music/Reelfold / persona music.dirs, the CC0 library, the built-in beds generated by
    Reelfold), none of them the track another video of the same group already has (a goal's videos each get their
    own) + "no music". Default: the best fit, unless she asked for no music. A fun reel: the tracks with a steady beat
    (its cuts follow the edit's music; a change re-cuts the reel to the new track), its drafted track first. Skipped
    when she gave a track."""
    rd = env.inputs.get("render") or {}
    style = rd.get("style") or env.params.get("style") or "calm"
    fun = style == "fun"
    if _given_track(env.params):
        return dict(options=[], skip=True, skip_reason="your music track is used")
    try:
        _p, cfg = _edit(env)
    except (OSError, ValueError):
        cfg = {}
    cur_track, cur_file = _fun_current(cfg) if fun else (None, None)
    if fun and cur_file and not cur_track:
        return dict(options=[], skip=True, skip_reason="a fun reel is cut to the music in its edit")
    text = _request_text(env)
    dur = _duration(rd["master"]) if rd.get("master") and os.path.exists(rd["master"]) else 60.0
    try:
        from vstudio import music as MU
        group = MU.group_of(env.project_dir)
        # the ranking leaves this video's own pick out and only counts the group's picks made before its own first
        # one: asking again (her answer, a resumed run) gives the same options in the same order
        ranked = MU.choose(text, style=style, project=env.project_dir, item=env.job, group=group,
                           shot_s=FUN_SHOT_S if fun else _edit_shot_s(cfg, False), need_beat=fun, min_duration=dur,
                           record_pick=not (cur_track or MU.pick_of(env.project_dir, env.job)))
    except Exception as e:  # noqa: BLE001  (no numpy / a broken library in this runtime: say so, no fake pick)
        return dict(options=[dict(id=0, kind="none", labels=dict(en="No music", zh="不配乐"), checked=True)],
                    default=dict(pick=0), default_reason=f"no music library in this runtime ({e})",
                    library_error=str(e)[:300], previews=[])
    if cur_track and cur_track not in [t["id"] for t in ranked[:N_TRACKS]]:
        cur = next((t for t in ranked if t["id"] == cur_track), None)    # the reel's own track is always offered
        if cur:
            ranked = ranked[:N_TRACKS - 1] + [cur]
    opts, previews = [], []
    for i, t in enumerate(ranked[:N_TRACKS]):
        o = dict(id=i, kind="track", track=t["id"], title=t["title"], mood=t["mood"], source=t["source"],
                 bpm=t.get("bpm"), license=t["license"], credit=t.get("credit"), why=_why(t, style, dur),
                 artist=t.get("artist"), labels=_label(t), checked=i == 0)
        if t["source"] in ("file", "library"):
            o["path"] = t["path"]
        else:
            try:                                    # a short, cached listen of the built-in (~0.4 s to make)
                o["path"] = MU.make(t["mood"], 20.0)
            except Exception:  # noqa: BLE001
                pass
        if o.get("path"):
            previews.append(dict(kind="audio", path=o["path"], label=o["labels"]["en"]))
        opts.append(o)
    none = len(opts)
    if not fun:                                     # a beat reel cannot drop its music: its cuts are on it
        opts.append(dict(id=none, kind="none", labels=dict(en="No music", zh="不配乐"), checked=False))
    pick = none if (not fun and (MU.wants_none(text) or not ranked)) else 0
    if fun and cur_track:                           # the reel is cut to its drafted track: that is the default
        pick = next((o["id"] for o in opts if o.get("track") == cur_track), 0)
    if pick != 0:
        for o in opts:
            o["checked"] = o["id"] == pick
    reason = ("you asked for no music" if ranked else "no track in the library") if pick == none \
        else opts[pick]["why"]
    return dict(options=opts, default=dict(pick=pick), default_reason=reason, previews=previews, fun=fun,
                group=group, digest=sha1_json([[o.get("track"), o.get("kind")] for o in opts])[:16])


def music_apply(a):
    """{pick: k} -> the item's ``music_pick`` (the music stage lays it under the master; a fun reel's edit gets the
    new beat track, so the reel is re-cut to it). The pick is noted for the group's / her recent videos' diversity."""
    k = int((a.value or {}).get("pick", 0))
    opts = a.payload.get("options") or []
    if not 0 <= k < len(opts):
        raise ValueError(f"music: pick {k} out of range")
    o = opts[k]
    from vstudio import music as MU
    pdir = getattr(getattr(a, "project", None), "dir", None)
    if o.get("kind") != "track":
        if pdir:
            MU.record("none", project=pdir, item=a.job, group=a.payload.get("group"))
        return dict(params=dict(music_pick=dict(none=True)))
    if pdir:
        MU.record(o["track"], project=pdir, item=a.job, group=a.payload.get("group"), title=o.get("title"))
    if a.payload.get("fun") and pdir:
        _set_fun_track(os.path.join(a.params.get("_item_dir") or os.path.join(pdir, "items", a.job), "work",
                                    "edit.json"), o)
    keep = ("track", "title", "mood", "source", "bpm", "license", "credit", "path", "artist")
    return dict(params=dict(music_pick={x: o[x] for x in keep if o.get(x) is not None}))


def _set_fun_track(path, o):
    """A fun reel's edit -> the picked beat track (copied next to the edit; nothing written when it already is)."""
    try:
        with open(path, encoding="utf-8") as f:
            cfg = json.load(f)
    except (OSError, ValueError):
        return
    if cfg.get("music_track") == o["track"]:
        return
    from vstudio import music as MU
    src = o.get("path") if o.get("source") != "builtin" else MU.make(o.get("mood") or "bright", 90.0)
    if not src or not os.path.exists(src):
        raise RuntimeError(f"the picked music file is gone: {src} (pick another track)")
    base = os.path.dirname(os.path.abspath(path))
    name = f"music_{str(o['track']).split(':', 1)[-1]}{os.path.splitext(src)[1]}"
    import shutil
    shutil.copyfile(src, os.path.join(base, name))
    cfg.update(music=name, music_track=o["track"])
    cfg.pop("music_start", None)
    tmp = path + ".part"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=2, ensure_ascii=False)
        f.write("\n")
    os.replace(tmp, path)


def _track_file(pick, dur):
    """The picked library track -> a playable file (a built-in is generated to the video's length, so it ends on
    its home chord with the picture)."""
    from vstudio import music as MU
    if pick.get("source") == "builtin":
        return MU.make(pick.get("mood") or str(pick["track"]).split(":", 1)[-1], round(dur, 2))
    path = pick.get("path") or pick.get("track")
    if (not path or not os.path.exists(path)) and str(pick.get("track") or "").startswith("lib:"):
        try:
            path = MU.resolve(pick["track"])
        except ValueError as e:
            raise RuntimeError(str(e)) from None
    if not path or not os.path.exists(path):
        raise RuntimeError(f"the picked music file is gone: {path} (pick another track)")
    return path


def music(env):
    master = env.inputs["render"]["master"]
    style = env.inputs["render"].get("style")
    given = _given_track(env.params)
    pick = env.params.get("music_pick") or {}
    if style == "fun" or (not given and (not pick or pick.get("none"))):
        why = "fun reel: music mixed by the render" if style == "fun" else "no music picked"
        return dict(master=master, files=[master], skipped=True, reason=why)
    out = os.path.join(env.item_dir, "out", "vlog_music.mp4")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    track = given or _track_file(pick, _duration(master))
    argv = [env.fmt("{python}"), os.path.join(env.workflow_dir, "scripts", "add_music.py"), master, track, out]
    plats = env.params.get("platforms") or []
    if plats:
        argv += ["--platform", plats[0]]              # the platform's loudness (-14 LUFS for the big ones)
    try:
        _p, cfg = _edit(env)
    except (OSError, ValueError):
        cfg = {}
    from vstudio import media
    if cfg.get("ambient_audio") and media.probe(master).get("has_audio"):
        argv += ["--ambient-db", "-12"]               # the place's own sound stays, 12 dB under the music
    env.run(argv, log="add_music.log")
    res = dict(master=out, files=[out], digest=file_sha(out), track=given or pick.get("track"),
               title=None if given else pick.get("title"), license=None if given else pick.get("license"))
    cr = None if given else pick.get("credit")
    if cr:                                            # CC BY: the credit goes into every platform's post copy
        res["credit"] = cr
        res["post"] = write_json(env.path("music_post.json"), dict(body=cr))
        res["files"].append(res["post"])
    return res


# --------------------------------------------------------------------------- framing (landscape -> vertical)
FILLS = (("follow", dict(en="Follow the subject", zh="跟随主体")),
         ("blur", dict(en="Fill with blur", zh="模糊填充")))


def _final_master(env):
    return (env.inputs.get("music") or {}).get("master") or (env.inputs.get("render") or {}).get("master")


def reframed_targets(master, platforms):
    """The targets whose canvas is another shape than the master (those get reframed)."""
    from vstudio import media
    from vstudio import platform as P
    info = media.probe(master)
    a = info["display_w"] / info["display_h"]
    out = []
    for p in P.parse_targets(list(platforms or []) or ["xiaohongshu"], master_aspect=a):
        if abs(p.w / p.h - a) > 0.01:
            out.append(p)
    return out


def _framing_previews(env, master, prof):
    """One frame of the master on the first reframed canvas, both ways (the follow crop placed where that frame's
    interest is; the blurred fill as exported) -> preview images."""
    import numpy as np
    from PIL import Image
    from vstudio import media
    from vstudio import reframe as R
    from vstudio import saliency
    from .common import grab_frame
    t = float(media.probe(master)["duration"]) * 0.4
    src = grab_frame(master, t, env.path("framing_frame.jpg"))
    im = np.asarray(Image.open(src).convert("RGB"))[..., ::-1].copy()
    h, w = im.shape[:2]
    tw, th = int(prof.w * 480 / prof.h) // 2 * 2, 480
    cw, _ch = R.crop_size(w, h, tw, th)
    an = saliency.Analyzer(person=False)
    col = an(im)["map"].sum(0)
    G = len(col)
    k = max(1, int(round(G * cw / w)))
    path, _s = R._window_path([col], k, 0.0, 0.05)
    x = min(max((path[0] + k / 2) / G * w - cw / 2, 0), w - cw)
    out = []
    for kind, mode in (("follow", "subject"), ("blur", "pad-blur")):
        pl = dict(target=[tw, th], src_w=w, src_h=h, mode_used=mode, rects=[[x, 0, cw, h]] if mode == "subject"
                  else None)
        img = R.frame_fn(pl)(0, im)
        p = env.path(f"framing_{kind}.jpg")
        Image.fromarray(np.ascontiguousarray(img[..., ::-1])).save(p, quality=86)
        out.append(dict(kind="image", path=p, label=dict(FILLS)[kind]["en"]))
    return out


def framing_payload(env, cp):
    """How a landscape master fills the vertical canvases: follow the subject (default) or the whole frame on a
    blurred fill. Skipped when every platform has the master's own shape."""
    master = _final_master(env)
    if not master or not os.path.exists(master):
        return dict(options=[], skip=True, skip_reason="no master yet")
    profs = reframed_targets(master, env.params.get("platforms"))
    if not profs:
        return dict(options=[], skip=True, skip_reason="every platform takes the video's own shape")
    try:
        previews = _framing_previews(env, master, profs[0])
    except Exception as e:  # noqa: BLE001  (a preview is a nicety: the choice stands without it)
        env.log(f"framing previews skipped: {str(e)[:160]}")
        previews = []
    by = dict((p["label"], p["path"]) for p in previews)
    opts = [dict(id=i, kind=k, labels=lab, checked=i == 0, **({"path": by[lab["en"]]} if lab["en"] in by else {}))
            for i, (k, lab) in enumerate(FILLS)]
    names = ", ".join(p.label for p in profs)
    return dict(options=opts, default=dict(pick=0), previews=previews, targets=[p.key for p in profs],
                default_reason=f"{names}: the camera follows what stands out in each shot (a shot that cannot be "
                               f"cropped is shown whole)",
                digest=sha1_json([p.key for p in profs])[:16])


def framing_apply(a):
    k = int((a.value or {}).get("pick", 0))
    if not 0 <= k < len(FILLS):
        raise ValueError(f"framing: pick {k} out of range")
    return dict(params=dict(reframe=FILLS[k][0]))


